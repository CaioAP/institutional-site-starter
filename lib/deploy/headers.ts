/**
 * Security and caching headers for static hosts. scripts/postgenerate.ts
 * writes them to `.output/public/_headers`, a format both Cloudflare Pages and
 * Netlify read. The CSP allows only what the starter uses, derived from the
 * build env: analytics hosts only when analytics is on, the form endpoint only
 * when the form posts to one.
 */
import type { BuildEnv } from './env'

type Directives = Record<string, string[]>

const origin = (url: string) => {
  try {
    return new URL(url).origin
  }
  catch {
    return undefined
  }
}

/**
 * @param scriptHashes sha256 hashes ("sha256-…") of every inline script in the
 *   generated HTML (Nuxt's config and import map, the consent head script).
 */
export function contentSecurityPolicy(env: BuildEnv, scriptHashes: string[]): string {
  const d: Directives = {
    'default-src': ['\'self\''],
    // Pagefind runs its search index as WebAssembly.
    'script-src': ['\'self\'', '\'wasm-unsafe-eval\'', ...[...new Set(scriptHashes)].sort().map(h => `'${h}'`)],
    // Vue binds a few inline style attributes; styles can't run code.
    'style-src': ['\'self\'', '\'unsafe-inline\''],
    'img-src': ['\'self\'', 'data:'],
    'font-src': ['\'self\''],
    'media-src': ['\'self\''],
    'connect-src': ['\'self\''],
    // Click-to-load video embeds only (privacy-enhanced YouTube, Vimeo).
    'frame-src': ['https://www.youtube-nocookie.com', 'https://player.vimeo.com'],
    'form-action': ['\'self\''],
    'object-src': ['\'none\''],
    'base-uri': ['\'self\''],
    'frame-ancestors': ['\'none\''],
  }

  if (env.formProvider === 'endpoint') {
    const endpoint = origin(env.formEndpoint)
    if (endpoint) {
      d['connect-src']!.push(endpoint)
      d['form-action']!.push(endpoint)
    }
  }

  if (env.analyticsProvider === 'plausible') {
    const plausible = origin(env.plausibleSrc)
    if (plausible) {
      d['script-src']!.push(plausible)
      d['connect-src']!.push(plausible)
    }
  }
  else if (env.analyticsProvider === 'ga4') {
    // Hosts from Google's CSP guide for GA4.
    d['script-src']!.push('https://*.googletagmanager.com')
    d['img-src']!.push('https://*.google-analytics.com', 'https://*.googletagmanager.com')
    d['connect-src']!.push('https://*.google-analytics.com', 'https://*.analytics.google.com', 'https://*.googletagmanager.com')
  }

  return Object.entries(d).map(([k, v]) => `${k} ${v.join(' ')}`).join('; ')
}

export interface HeaderRule {
  path: string
  headers: Record<string, string>
}

export function headerRules(env: BuildEnv, scriptHashes: string[]): HeaderRule[] {
  const security: Record<string, string> = {
    'Content-Security-Policy': contentSecurityPolicy(env, scriptHashes),
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'DENY',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()',
    'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
    'Cross-Origin-Opener-Policy': 'same-origin',
  }
  if (env.siteEnv === 'preview') security['X-Robots-Tag'] = 'noindex'

  return [
    { path: '/*', headers: security },
    // Content-hashed build assets never change.
    { path: '/_nuxt/*', headers: { 'Cache-Control': 'public, max-age=31536000, immutable' } },
    // Font file names don't change when the package is upgraded: 30 days.
    { path: '/fonts/*', headers: { 'Cache-Control': 'public, max-age=2592000' } },
    // Image variants keep their URL when the source image is replaced, so
    // they're cached for a week, not forever.
    { path: '/_ipx/*', headers: { 'Cache-Control': 'public, max-age=604800' } },
  ]
}

/** Serializes rules in the `_headers` format (Cloudflare Pages, Netlify). */
export function formatHeadersFile(rules: HeaderRule[]): string {
  const blocks = rules.map(r => [r.path, ...Object.entries(r.headers).map(([k, v]) => `  ${k}: ${v}`)].join('\n'))
  return `# Generated by scripts/postgenerate.ts from lib/deploy/headers.ts. Do not edit.\n${blocks.join('\n')}\n`
}

/** Parses the `_headers` format (used by the local static server in tests). */
export function parseHeadersFile(text: string): HeaderRule[] {
  const rules: HeaderRule[] = []
  for (const line of text.split('\n')) {
    if (!line.trim() || line.trimStart().startsWith('#')) continue
    if (!/^\s/.test(line)) {
      rules.push({ path: line.trim(), headers: {} })
      continue
    }
    const i = line.indexOf(':')
    if (i > 0 && rules.length) rules.at(-1)!.headers[line.slice(0, i).trim()] = line.slice(i + 1).trim()
  }
  return rules
}

/** Headers for a request path: every matching rule, later rules win. `*` matches anything. */
export function headersFor(rules: HeaderRule[], path: string): Record<string, string> {
  const out: Record<string, string> = {}
  for (const r of rules) {
    const re = new RegExp(`^${r.path.split('*').map(s => s.replace(/[.+?^${}()|[\]\\]/g, '\\$&')).join('.*')}$`)
    if (re.test(path)) Object.assign(out, r.headers)
  }
  return out
}
